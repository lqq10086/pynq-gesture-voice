def collect():
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / 'collector.tcl'
    path.write_text(COLLECTOR, encoding='utf-8')
    dcp = BUILD / 'final_routed.dcp'
    before = sha(dcp)
    command = [r'D:\Tools\FPGA\Vivado\2023.1\bin\vivado.bat', '-mode', 'batch', '-source', str(path),
               '-log', str(OUT/'vivado.log'), '-journal', str(OUT/'vivado.jou'), '-tclargs', str(dcp), str(OUT), sys.executable]
    with (OUT/'console.log').open('w', encoding='utf-8') as stream:
        run = subprocess.run(command, cwd=OUT, stdout=stream, stderr=subprocess.STDOUT)
    complete = (run.returncode == 0 and before == sha(dcp) and
                'WB1_INDEPENDENT_INSPECTION_COMPLETE' in read(OUT/'console.log'))
    record = dict(returncode=run.returncode, complete=complete, dcp_sha256=before,
                  collector_sha256=sha(path), reviewer_sha256=sha(__file__), command=command,
                  evidence_sha256={p.name:sha(p) for p in OUT.iterdir() if p.suffix in ('.log','.jou','.tsv','.rpt')})
    (OUT/'collection.json').write_text(json.dumps(record, indent=2)+'\n', encoding='utf-8')
    require(complete, 'Supplemental collector incomplete; inspect console.log')


def check_collect(dcp):
    record = json.loads(read(OUT/'collection.json'))
    require(record['complete'] is True and record['returncode'] == 0 and record['dcp_sha256'] == dcp,
            'Supplemental collection incomplete/wrong DCP')
    require(record['collector_sha256'] == sha(OUT/'collector.tcl') and read(OUT/'collector.tcl') == COLLECTOR,
            'Supplemental collector source changed')
    for name, digest in record['evidence_sha256'].items():
        require(sha(OUT/name) == digest, 'Supplemental evidence changed: '+name)
    assert_binding(OUT/'independent_facts.tsv', dcp, OUT/'collector.tcl')
    require('WB1_INDEPENDENT_INSPECTION_COMPLETE' in read(OUT/'console.log'), 'Collector completion absent')
    return True


def check_wb(data, extra):
    result = {}
    cells = {r[1]:r for r in data if r[0] == 'CELL'}
    for name in ('command_cdc_i','result_cdc_i'):
        payload = [r for r in data if r[0] == 'PAYLOAD' and r[1] == name]
        require(len(payload) == 1, 'Missing WB payload counts')
        constants = [(r[2],r[3],r[4]) for r in data if r[0] == 'CONSTANT' and r[1] == name]
        result[name] = check_payload(data, name, int(payload[0][2]), int(payload[0][3]), 10.0, constants)
        sync = [r for r in cells.values() if r[1].startswith('wb_bridge_i/'+name+'/') and 'syncstages_ff_reg' in r[1]]
        require(len(sync) == 6 and all(r[3] in ('1','TRUE') for r in sync), 'WB handshake must have two three-stage synchronizers')
        logical = [r for r in extra if r[0] == 'LOGICAL' and r[1] == name]
        require(len(logical) == 128 and {int(r[2]) for r in logical} == set(range(128)), 'Not all logical payload bits accounted')
        dst = {r[3][:-2] for r in data if r[0] == 'PATH' and r[1] == name} | {r[0][:-2] for r in constants}
        counts = Counter()
        for row in logical:
            require(len(row) == 6 and len(row[4].split()) == 1, 'Ambiguous logical bit driver')
            driver, ref = row[4], row[5]
            if ref in ('GND','VCC'):
                require(driver.endswith(('/G','/P')), 'Malformed constant bit')
                counts[ref] += 1
            else:
                require(ref.startswith('FD') and driver.endswith('/Q') and driver[:-2] in dst,
                        'Logical bit not mapped to covered destination FF: '+str(row))
                counts['registered'] += 1
        result[name]['logical_bits'] = dict(counts)
    return result


def check_snapshot(data, const):
    result = {}
    for name, src, dst, req in [('cam',451,451,10.0),('mem',365,417,7.0)]:
        payload = [r for r in data if r[:2] == ['PAYLOAD', name]]
        require(len(payload) == 1 and payload[0][2:] == ['SRC_COUNT',str(src),'DST_COUNT',str(dst)], 'Snapshot register count drift')
        constants = [(r[1],r[3],r[4]) for r in const if r[0] == 'CONSTANT_DEST'] if name == 'mem' else []
        result[name] = check_payload(data, name, src, dst, req, constants)
        if name == 'mem':
            require(len(constants) == 52 and all(r[2] == 'GND' for r in constants), 'Snapshot constants drift')
        sync = [r for r in data if r[:2] == ['HANDSHAKE_SYNC',name]]
        require(len(sync) == 6 and all(r[3] in ('1','TRUE') for r in sync), 'Snapshot handshake sync chain drift')
    return result


def cell_maps(extra):
    return ({r[1]:r for r in extra if r[0] == 'CELL'}, {r[1]:r for r in extra if r[0] == 'PIN'})


def check_serial(extra, prefix, count, clock):
    cells, pins = cell_maps(extra)
    for index in range(count):
        cell = f'{prefix}[{index}]'
        require(cell in cells and cells[cell][2].startswith('FD') and cells[cell][3] in ('1','TRUE'), 'Missing ASYNC_REG chain cell '+cell)
        require(pins[cell+'/C'][6] == clock, 'Wrong synchronizer clock')
        if index:
            require(pins[cell+'/D'][4] == f'{prefix}[{index-1}]/Q', 'Synchronizer is not a serial FF chain')
    timing = [r for r in extra if r[:2] == ['SERIAL_TIMING',prefix]]
    require(len(timing) == 2*(count-1) and {(int(r[2]),r[3]) for r in timing} ==
            {(i,t) for i in range(1,count) for t in ('max','min')}, 'Missing synchronizer stage timing')
    for row in timing:
        finite(row[5], True)
    return min(float(r[5]) for r in timing)


def check_controls(extra):
    cells, pins = cell_maps(extra)
    abort = 'wb_bridge_i/abort_cdc_i/syncstages_ff_reg'
    check_serial(extra, abort, 3, 'clk50')
    source = 'wb_bridge_i/abort_cdc_i/src_ff_reg'
    require(pins[source+'/C'][6] == 'clk_fpga_0', 'Abort source clock is not AXI')
    fatal = pins[source+'/D'][4]
    require(fatal.endswith('/wb_fatal_reg/Q') and cells[fatal[:-2]][2].startswith('FD'), 'Abort is not sourced from sticky endpoint fatal FF')
    require(pins[abort+'[0]/D'][4] == source+'/Q', 'Abort first-stage source drift')
    controls = {r[1]:r for r in extra if r[0] == 'CONTROL'}
    loads=[r[1] for r in extra if r[0]=='CORE_ABORT_LOAD']
    # Vivado can place shared combinational terms under mode_i/wb_bridge_i;
    # functional sequential endpoints, not the LUT hierarchy, define ownership.
    require(loads and all(r[2].startswith('LUT') for r in extra if r[0]=='CORE_ABORT_LOAD'),
            'Final abort has missing or unreviewed direct loads')
    fanout=[r[1].split(',') for r in extra if r[0]=='ABORT_FANOUT']
    require(len(fanout)==1 and any(p.startswith('wb_control_i/fatal_latched_reg/') for p in fanout[0]) and
            any(p.startswith('wb_control_i/capture_freeze_reg/') for p in fanout[0]),'Synchronized abort does not reach core terminal/freeze logic')
    require(all(p.startswith(('wb_control_i/','camera_config_i/')) for p in fanout[0]),'Unreviewed abort functional endpoint')
    check_serial(extra, 'color_capture_freeze_sync_reg', 2, 'cam_pclk_shifted')
    lut = controls['color_capture_freeze_sync_reg[0]/D'][2][:-2]
    require(cells[lut][2:] == ['LUT2','','4\'hE'], 'Freeze combining function is not the reviewed two-input OR')
    sources = {pins[lut+'/I0'][4],pins[lut+'/I1'][4]}
    require(sources == {'camera_config_i/capture_freeze_reg/Q','wb_control_i/capture_freeze_reg/Q'}, 'Freeze OR source identity drift')
    for source in sources:
        require(pins[source[:-2]+'/C'][6] == 'clk50', 'Freeze source clock drift')
    fanout = [r for r in extra if r[0] == 'FREEZE_FANOUT']
    require(len(fanout) == 1 and fanout[0][1] == 'capture_enable_cam_reg/D', 'Freeze final stage has an unreviewed functional sink')
    require(pins['capture_enable_cam_reg/C'][6] == 'cam_pclk_shifted', 'Capture enable destination clock drift')
    return dict(abort='sticky AXI fatal -> registered source -> 3 ASYNC_REG clk50 stages -> core abort',
                freeze='two clk50 FF sources -> OR -> 2 ASYNC_REG camera stages -> registered capture enable; functional mutual exclusion/reset proof is separately required')


def cdc_inventory(text):
    data = base.cdc_rows(text)
    header = text.split('Source Clock:',1)[0]
    matches = re.findall(r'^(CDC-\d+)\s+(Info|Warning|Critical)\s+(\d+)\s+.+$', header,re.M)
    require(len(matches) == len(re.findall(r'^CDC-\S+\s+.*$',header,re.M)), 'Unparsed CDC summary')
    expected = {(rule,severity):int(count) for rule,severity,count in matches}
    require(expected == Counter((r['id'],r['severity']) for r in data), 'CDC summary/detail mismatch')
    unique([base.cdc_key(r) for r in data], 'Duplicate CDC path')
    return data


def check_cdc(text, historical, wb, extra):
    prior = {(base.cdc_key(r),r['severity']) for r in cdc_inventory(historical)}
    current = cdc_inventory(text)
    cells,pins = cell_maps(extra)
    new = []
    for row in current:
        if (base.cdc_key(row),row['severity']) in prior:
            continue
        # New single-bit XPM crossings must terminate on an independently proved
        # first synchronizer FF; never accept arbitrary new Info rows.
        dest = row['destination']
        if (row['src_clock'],row['dst_clock'],row['source'],dest) == (
                'clk50','cam_pclk_shifted','wb_control_i/capture_freeze_reg/C','color_capture_freeze_sync_reg[0]/D') and (
                row['id'],row['severity']) in (('CDC-3','Info'),('CDC-10','Critical')):
            check_controls(extra)
            check_freeze_lifecycle()
            new.append(dict(row,review='Exact two-source OR; source lifecycle excludes opposed transitions while capture is enabled; boot/reset masked by config_done/MMCM plus 3-stage camera reset. Raw Critical retained.'))
            continue
        if row['id'] == 'CDC-3' and row['severity'] == 'Info' and dest.startswith('wb_bridge_i/'):
            require(dest.endswith('syncstages_ff_reg[0]/D') and dest in pins, 'Unreviewed new XPM endpoint')
            require(pins[dest][4][:-2] + '/C' == row['source'], 'CDC source differs from physical first-stage driver')
            require(cells[dest[:-2]][3] in ('1','TRUE'), 'New CDC chain lacks ASYNC_REG')
            require(pins[dest[:-2]+'/C'][6]==row['dst_clock'],'CDC destination clock does not match physical FF')
            new.append(row); continue
        # No new warning/critical waiver is installed automatically. In particular,
        # freeze-OR CDC needs a current-DCP review even if its source proof is sound.
        raise ValueError('Unreviewed new CDC: '+json.dumps(row))
    required={base.cdc_key(r) for r in cdc_inventory(historical) if r['severity']!='Info'}
    require(required.issubset(base.cdc_key(r) for r in current),'Historical warning/reset crossing disappeared without review')
    require(len(new)==7,'New CDC inventory differs from the reviewed five XPM plus two freeze rows')
    return dict(counts=dict(Counter(r['severity'] for r in current)), newly_reviewed_rows=new)


