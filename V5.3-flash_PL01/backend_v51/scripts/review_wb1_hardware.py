def check_drc(text, policy, explicit=None):
    blocks = base.drc_blocks(text)
    count = re.search(r'Violations found:\s*(\d+)', text)
    require(count and int(count[1]) == len(blocks), 'DRC detail/summary mismatch')
    accepted={(r['rule'],r['severity'],r['body']) for r in explicit['accepted']+explicit.get('independent_report_variants',[])} if explicit else set()
    if explicit:
        require(set(blocks).issubset(accepted) and len(set(blocks))==len(blocks)==len(explicit['accepted']) and
                Counter(rule for rule,severity,body in blocks)==explicit['counts'],'Current DRC inventory differs from the explicit per-body review')
    for rule,severity,body in blocks:
        require(severity in ('Warning','Advisory'), 'Blocking DRC: '+rule)
        require((rule,severity,body) in accepted or rule+'|'+body in policy['drc_details'], 'Unreviewed DRC '+rule+': '+body)
    return dict(counts=dict(Counter(rule for rule,severity,body in blocks)), exact_reviewed_details=len(blocks))


def check_old_objects(text, historical=None):
    # Re-prove old exceptions on this checkpoint. No old object report is used.
    lut_blocks = re.findall(r'^CELL ([^\n]+)\n(.*?)(?=^CELL |^NETS |^VIOLATION )',text,re.M|re.S)
    pdcn = [(name,body) for name,body in lut_blocks if 'gpregsm1.user_valid_i_1' in name]
    require(len(pdcn) == 6, 'Expected six reviewed vendor protocol-converter LUTs')
    for name,body in pdcn:
        require('REF_NAME = LUT4' in body and "INIT = 16'hAFAA" in body, 'Protocol converter LUT truth table changed')
        value = int('AFAA',16)
        require(all(((value>>i)&1) == ((value>>(i^2))&1) for i in range(16)), 'LUT is not insensitive to I1')
        require(re.search(re.escape(name)+r'/I1 DIR=IN NET=',body), 'Missing actual unused LUT input')
    nets = re.findall(r'^NET ([^\n]+) ROUTE_STATUS=(\S+)\n(.*?)(?=^NET |^VIOLATION |^SINGLE_BIT_FRAME_CDC)',text,re.M|re.S)
    require(len(nets) == 66 and all(status == 'NOLOADS' and 'DIR=IN' not in body and
            re.search(r'^  PORTS\s*$',body,re.M) and 'DIR=OUT' in body for _,status,body in nets), 'Unproven dangling-route advisory')
    if historical is not None:
        require({name for name,_,_ in nets} == set(re.findall(r'^NET ([^\n]+) ROUTE_STATUS=',historical,re.M)), 'New dangling vendor net identity')
        require({name for name,_ in pdcn} == set(re.findall(r'^CELL ([^\n]*gpregsm1.user_valid_i_1)$',historical,re.M)), 'New vendor LUT identity')
    bufg = {name:body for name,body in lut_blocks if 'REF_NAME = BUFG' in body}
    prefix = 'system_i/system_i/processing_system7_0/inst/buffer_fclk_clk_0.FCLK_CLK_0_BUFG'
    require(not bufg or set(bufg)=={prefix,prefix+'_replica'}, 'Unexpected PS clock-buffer advisory topology')
    def net(name,pin):
        match=re.search(re.escape(name+'/'+pin)+r' DIR=\S+ NET=(\S+) BEL=',bufg[name])
        require(match,'Missing BUFG pin'); return match[1]
    if bufg:
        require(net(prefix,'I')==net(prefix+'_replica','O'),'Clock-buffer cascade connection changed')
        require(all(body.count(' = clk_fpga_0')==2 for body in bufg.values()),'PS buffer clock propagation changed')
    else:
        require('VIOLATION PLBUFGOPT-1' not in text,'Clock-buffer advisory lacks object proof')
    reset = re.findall(r'^RESET_STAGE (\S+) REF=(\S+) ASYNC_REG=(\S+) INIT=(\S+)',text,re.M)
    require({r[0] for r in reset} == {f'cam_reset_pipe_reg[{i}]' for i in range(3)} and
            all(r[1:] == ('FDPE','1',"1'b1") for r in reset), 'Reset release chain changed')
    require(re.search(r'ASSERT_DRIVER \S+ REF=LUT2 INIT=4\'h7',text), 'Reset assertion is not the reviewed NAND')
    assert_pins = re.findall(r'ASSERT_PIN (\S+) DIR=(\S+) REF=(\S+)',text)
    require(len(assert_pins) == 4 and sum(r[1:] == ('IN','FDPE') for r in assert_pins) == 3, 'Reset-only assertion fanout changed')
    stage_pins=dict(re.findall(r'STAGE_PIN (\S+) DIR=\S+ NET=(\S+)',text))
    for i in (1,2):
        require(stage_pins[f'cam_reset_pipe_reg[{i}]/D']==stage_pins[f'cam_reset_pipe_reg[{i-1}]/Q'],'Reset release is not serial')
    require(len({stage_pins[f'cam_reset_pipe_reg[{i}]/C'] for i in range(3)})==1,'Reset release clock drift')
    require('INPUT_DRIVER camera_config_i/config_done_reg/Q REF=FDRE' in text and
            'INPUT_DRIVER camera_sample_mmcm_i/LOCKED REF=MMCME2_ADV' in text, 'Reset assertion source identity changed')
    for token in ('CLKIN1_PERIOD=11.800','CLKFBOUT_MULT_F=8.000','CLKOUT0_DIVIDE_F=8.000','CLKOUT0_PHASE=90.000','DIVCLK_DIVIDE=1'):
        require(token in text, 'Camera MMCM setting changed: '+token)
    release = re.findall(r'^RESET_RELEASE_TIMING (\S+) (max|min) (\S+)',text,re.M)
    require({(a,b) for a,b,c in release} == {(p,t) for p in ('0->1','1->2') for t in ('max','min')}, 'Reset release timing incomplete')
    for a,b,c in release: finite(c,True)
    require(text.count('ASYNC_REG=1',text.find('HANDSHAKE_SYNC_STAGES'),text.find('SINGLE_BIT_TIMING')) == 6, 'Frame handshake synchronizer stages changed')
    return dict(protocol_converter_luts=6, no_load_nets=66, reset_release_stages=3,
                reset_min_slack_ns=min(float(r[2]) for r in release))


def check_hwh(path):
    doc = ET.parse(path)
    ranges = [el.attrib for el in doc.iter('MEMRANGE') if el.get('INSTANCE') in ('camera_control_0','conv_accel_0')]
    for name,baseaddr in [('camera_control_0',0x41220000),('conv_accel_0',0x43c00000)]:
        found = [r for r in ranges if r['INSTANCE'] == name]
        require(found and all(int(r['BASEVALUE'],0)==baseaddr and int(r['HIGHVALUE'],0)==baseaddr+0xffff for r in found), 'Address map drift '+name)
    modules=[el for el in doc.iter('MODULE') if el.get('INSTANCE')=='camera_control_0']
    require(len(modules)==1 and modules[0].get('VLNV')=='xilinx.com:module_ref:camera_control_axi_v33:1.0','Wrong camera control module')
    ports={p.get('NAME'):p for p in modules[0].iter('PORT')}
    external={p.get('NAME'):p for parent in doc.iter('EXTERNALPORTS') for p in parent}
    for name,internal,direction,width in [('WB_COMMAND','sensor_command','O',128),('WB_SEND','sensor_command_send','O',1),
            ('WB_RECEIVED','sensor_command_received','I',1),('WB_RESULT','sensor_result','I',128),
            ('WB_RESULT_VALID','sensor_result_valid','I',1),('WB_ABORT','sensor_abort','O',1)]:
        for element in (external[name],ports[internal]):
            require(element.get('DIR')==direction and int(element.get('LEFT','0'))-int(element.get('RIGHT','0'))+1==width,'WB port width/direction drift '+name)
        require([e.attrib for e in external[name].iter('CONNECTION')]==[dict(INSTANCE='camera_control_0',PORT=internal)],'Wrong WB external connection '+name)
        require([e.attrib for e in ports[internal].iter('CONNECTION')]==[dict(INSTANCE='External_Ports',PORT=name)],'Wrong WB internal connection '+name)
        require(external[name].get('SIGNAME')==ports[internal].get('SIGNAME'),'WB signal identity drift')
    for name in ('s_axi_awaddr','s_axi_araddr'):
        require(ports[name].get('LEFT')=='7' and ports[name].get('RIGHT')=='0','WB address width cannot cover 0xd8')
    for element in (ports['s_axi_aclk'],external['CONTROL_CLK']):
        require(element.get('CLKFREQUENCY')=='100000000' and
                [e.attrib for e in element.iter('CONNECTION')]==[dict(INSTANCE='processing_system7_0',PORT='FCLK_CLK0')],'Wrong WB control clock')
    require("32'h57423431" in read(ROOT/'hardware/rtl/camera_control_axi.v'), 'Wrong WB ABI source')
    return ranges


