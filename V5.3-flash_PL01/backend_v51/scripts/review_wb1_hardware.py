def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def read(path):
    return Path(path).read_text(encoding='utf-8', errors='replace')


def finite(value, positive=False):
    value = float(value)
    require(math.isfinite(value) and (value > 0 if positive else value >= 0),
            'Invalid or nonpositive timing value: ' + str(value))
    return value


def rows(path):
    return [line.split('\t') for line in read(path).splitlines() if line.strip()]


def unique(items, message):
    require(len(items) == len(set(items)), message)
    return set(items)


def assert_binding(path, dcp, inspector):
    text = read(path)
    require(re.search(r'^DCP_SHA256[\t ]' + re.escape(dcp) + r'$', text, re.M),
            'Wrong DCP binding: ' + str(path))
    require(re.search(r'^INSPECTOR_SHA256[\t ]' + sha(inspector) + r'$', text, re.M),
            'Wrong inspector binding: ' + str(path))
    return True


def check_payload(data, name, source_count, destination_count, requirement, constants):
    paths = [r for r in data if r[0] == 'PATH' and r[1] == name]
    ends = unique([r[3] for r in paths], 'Duplicate timed destination: ' + name)
    unique([r[0] for r in constants], 'Duplicate constant destination: ' + name)
    require(not ends.intersection(r[0] for r in constants), 'Timed/constant overlap')
    require(len(paths) + len(constants) == destination_count, 'Incomplete payload destination coverage: ' + name)
    require(source_count > 0 and len(paths) > 0, 'Empty payload path set')
    for row in paths:
        require(len(row) == 7, 'Malformed payload timing row')
        require(abs(finite(row[4], True) - requirement) < .001, 'Unexpected payload max-delay requirement')
        finite(row[5]); finite(row[6], True)
        require('/src_hsdata_ff_reg[' in row[2] and row[2].endswith('/C') and
                '/dest_hsdata_ff_reg[' in row[3] and row[3].endswith('/D'), 'Wrong payload endpoints')
    for pin, driver, ref in constants:
        require(ref in ('GND', 'VCC') and len(driver.split()) == 1 and driver.endswith(('/G', '/P')),
                'Untimed destination lacks a unique actual constant primitive: ' + pin)
    return dict(source_registers=source_count, destination_registers=destination_count,
                timed=len(paths), constants=len(constants), min_slack_ns=min(float(r[6]) for r in paths))


